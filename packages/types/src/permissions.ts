export function permissionsForRoles(roles: readonly string[], custom: Record<string, readonly string[]> = {}): Set<Permission> {
  const set = new Set<Permission>();
  for (const role of roles) {
    const perms = (DEFAULT_ROLE_PERMISSIONS as Record<string, readonly Permission[] | undefined>)[role] ?? custom[role] ?? [];
    for (const p of perms) {
      if ((PERMISSIONS as readonly string[]).includes(p)) set.add(p as Permission);
    }
  }
  return set;
}

