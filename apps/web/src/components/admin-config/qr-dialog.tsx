"use client";

import { Button, Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle, Skeleton } from "@pcos/ui";
import { useQuery } from "@tanstack/react-query";
import { Download, ExternalLink, QrCode } from "lucide-react";
import { UrlText } from "@/components/url-text";
import { get } from "@/lib/api";
import { useT } from "@/lib/i18n";
import type { QrCodes, QrKind } from "./types";
import { CopyButton, QueryError } from "./ui";

const KINDS: { kind: QrKind; title: string; description: string; missing: string }[] = [
  {
    kind: "localRegistration",
    title: "Registration (venue Wi-Fi)",
    description: "Players on the venue network open the registration page.",
    missing: "Set the venue's local address in Local network settings.",
  },
  {
    kind: "localLive",
    title: "Live page (venue Wi-Fi)",
    description: "Clock, blinds and seat list on players' phones.",
    missing: "Set the venue's local address in Local network settings.",
  },
  {
    kind: "publicRegistration",
    title: "Registration (Internet)",
    description: "For posters and social media; needs the public address.",
    missing: "No public address is configured for this venue.",
  },
  {
    kind: "telegram",
    title: "Telegram bot",
    description: "Opens the club bot directly on this tournament.",
    missing: "Enable the Telegram bot to get this link.",
  },
];

/** QR codes for registration / live page / Telegram deep link (GET /tournaments/:id/qr). */
export function QrCodesDialog({ tournamentId, slug, open, onOpenChange }: { tournamentId: string; slug: string; open: boolean; onOpenChange: (open: boolean) => void }) {
  const t = useT();
  const q = useQuery({
    queryKey: ["cfg", "qr", tournamentId],
    queryFn: () => get<QrCodes>(`/api/v1/tournaments/${tournamentId}/qr`),
    enabled: open,
    staleTime: 60_000,
  });
  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent wide>
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <QrCode className="size-5 text-primary" /> {t("QR codes")}
          </DialogTitle>
          <DialogDescription>{t("Print these or show them on a screen so players can register and follow the tournament.")}</DialogDescription>
        </DialogHeader>
        {q.isError && <QueryError error={q.error} onRetry={() => void q.refetch()} />}
        <div className="grid gap-4 sm:grid-cols-2">
          {KINDS.map(({ kind, title, description, missing }) => {
            const link = q.data?.links[kind] ?? null;
            const img = q.data?.qr[kind] ?? null;
            return (
              <div key={kind} className="grid content-start gap-3 rounded-lg border border-border p-4">
                <div>
                  <div className="font-medium">{t(title)}</div>
                  <div className="text-xs text-muted-foreground">{t(description)}</div>
                </div>
                {q.isLoading ? (
                  <Skeleton className="aspect-square w-full max-w-48" />
                ) : img && link ? (
                  <>
                    {/* eslint-disable-next-line @next/next/no-img-element -- data URL generated by the edge server */}
                    <img src={img} alt={t(title)} className="aspect-square w-full max-w-48 rounded-md bg-white p-2" />
                    <div className="font-mono text-xs text-muted-foreground [overflow-wrap:anywhere]">
                      <UrlText url={link} />
                    </div>
                    <div className="flex flex-wrap gap-2">
                      <CopyButton value={link} label={t("Copy link")} />
                      <Button asChild variant="outline" size="sm">
                        <a href={img} download={`${slug}-${kind}.png`}>
                          <Download /> {t("PNG")}
                        </a>
                      </Button>
                      <Button asChild variant="ghost" size="sm">
                        <a href={link} target="_blank" rel="noreferrer">
                          <ExternalLink /> {t("Open")}
                        </a>
                      </Button>
                    </div>
                  </>
                ) : (
                  <p className="text-sm text-muted-foreground">{t(missing)}</p>
                )}
              </div>
            );
          })}
        </div>
      </DialogContent>
    </Dialog>
  );
}
